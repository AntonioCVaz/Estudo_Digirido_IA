"""## 3. Hipóteses e Estimação (Etapa 1)
Nesta etapa, tomamos a decisão analítica mais importante do projeto. Inicialmente, cogitamos usar a distribuição Normal para Ingressantes ($X_1$) e Matrículas ($X_2$). No entanto, ao plotarmos os histogramas, notamos que a enorme maioria dos cursos brasileiros é muito pequena (pico próximo a zero), com poucos cursos enormes gerando uma longa cauda à direita. A Normal ficava achatada e projetava densidade para valores negativos.

Para provar isso, criamos um teste formal comparando a Normal com a **Exponencial** via Critério de Informação de Akaike (AIC) e teste de Kolmogorov-Smirnov (KS). A Exponencial venceu com uma ordem de grandeza de vantagem.

Portanto, nossas hipóteses assumidas são:
*   $X_1$ e $X_2$ (Contínuas): **Distribuição Exponencial** ($\lambda = 1 / \mu$).
*   $X_3$ (Categórica binária): **Distribuição de Bernoulli**.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

df_treino = pd.read_csv('treino.csv', sep=';')
df_publica = df_treino[df_treino['Y_REDE'] == 0]
df_privada = df_treino[df_treino['Y_REDE'] == 1]

# Extração das Probabilidades a Priori P(Y=c)
n_total = len(df_treino)
p_y0 = len(df_publica) / n_total
p_y1 = len(df_privada) / n_total

def verossimilhanca_exponencial(x, lam):
    """Fórmula da densidade Exponencial calculada manualmente: f(x) = lambda * exp(-lambda * x)"""
    return lam * np.exp(-lam * x)

# Extraindo parâmetros de X1 (QT_ING)
lambda_x1_y0 = 1 / df_publica['QT_ING'].mean()
lambda_x1_y1 = 1 / df_privada['QT_ING'].mean()

# Extraindo parâmetros de X2 (QT_MAT)
lambda_x2_y0 = 1 / df_publica['QT_MAT'].mean()
lambda_x2_y1 = 1 / df_privada['QT_MAT'].mean()

# Extraindo parâmetros de X3 (X3_MODALIDADE)
p_x3_y0 = df_publica['X3_MODALIDADE'].mean()
p_x3_y1 = df_privada['X3_MODALIDADE'].mean()

