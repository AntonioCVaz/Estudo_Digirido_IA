"""## 4. Análise Univariada de X1 (Ingressantes)
O roteiro nos pede para diferenciar **Verossimilhança** ($p(x|Y=c)$) de **Probabilidade a posteriori** ($P(Y=c|x)$). A verossimilhança nos diz apenas o quão comum é uma observação assumindo que já sabemos a classe (é uma densidade, pode passar de 1). Já a probabilidade a posteriori aplica o Teorema de Bayes para misturar essa evidência com o *prior* do Brasil (95% privada), nos dando a chance real de o curso ser de tal rede (somando 100%).

Como adotamos duas Exponenciais, encontrar a fronteira de decisão (onde as probabilidades se cruzam) exige resolver uma equação estritamente **linear**, não quadrática.
"""

# 1. Razão de Verossimilhanças (Lambda)
def razao_verossimilhanca_exp(x, lam0, lam1):
    return verossimilhanca_exponencial(x, lam1) / verossimilhanca_exponencial(x, lam0)

exemplo_x1 = 100
lam_x1 = razao_verossimilhanca_exp(exemplo_x1, lambda_x1_y0, lambda_x1_y1)
print(f"Para x=100 ingressantes, a Razão Λ(x) é {lam_x1:.4f} (Favorece Y=0, Pública).")

# 2. Teorema de Bayes (Posteriori)
def posterior_exp(x, lam0, p0, lam1, p1):
    l0 = verossimilhanca_exponencial(x, lam0) * p0
    l1 = verossimilhanca_exponencial(x, lam1) * p1
    return l0 / (l0 + l1), l1 / (l0 + l1)

post_0, post_1 = posterior_exp(exemplo_x1, lambda_x1_y0, p_y0, lambda_x1_y1, p_y1)
print(f"Posteriori para x=100 -> P(Y=0|x): {post_0:.4f} | P(Y=1|x): {post_1:.4f}")

# 3. Fronteira de Decisão
def fronteira_decisao_exp(lam0, p0, lam1, p1):
    """Derivação algébrica para igualar os posteriores exponenciais"""
    return (np.log(p1 * lam1) - np.log(p0 * lam0)) / (lam1 - lam0)

front_x1 = fronteira_decisao_exp(lambda_x1_y0, p_y0, lambda_x1_y1, p_y1)
print(f"A fronteira de decisão de X1 ocorre exatamente em: {front_x1:.1f} ingressantes.")

"""## 5. Análise Univariada de X2 (Matrículas)
Aplicamos a mesma lógica algébrica para o total de matrículas. Esperamos que a fronteira seja numericamente maior aqui, já que turmas acumulam alunos de vários semestres.
"""

exemplo_x2 = 400
lam_x2 = razao_verossimilhanca_exp(exemplo_x2, lambda_x2_y0, lambda_x2_y1)
post2_0, post2_1 = posterior_exp(exemplo_x2, lambda_x2_y0, p_y0, lambda_x2_y1, p_y1)

print(f"Para x=400 matrículas, a Razão Λ(x) é {lam_x2:.4f} (Favorece Pública).")
print(f"Posteriori para x=400 -> P(Y=0|x): {post2_0:.4f} | P(Y=1|x): {post2_1:.4f}")

front_x2 = fronteira_decisao_exp(lambda_x2_y0, p_y0, lambda_x2_y1, p_y1)
print(f"A fronteira de decisão de X2 ocorre exatamente em: {front_x2:.1f} matrículas.")

"""## 6. Análise Univariada de X3 (Modalidade)
Sendo categórica (Bernoulli), $X_3$ não possui uma "fronteira contínua", mas sim uma regra lógica por categoria.

Para a comparação qualitativa do **poder de discriminação**, não podemos usar o D de Cohen (que exige normalidade). Para sermos matematicamente rigorosos com nossas distribuições, calculamos o **Coeficiente de Sobreposição (OVL)**. A área não sobreposta (`1 - OVL`) nos dá o ranking de qual variável separa melhor as classes sozinha.
"""

# Regra de decisão da variável categórica
print(f"Probabilidades se Presencial (0): P(Y=0)={1-p_x3_y0:.4f} | P(Y=1)={1-p_x3_y1:.4f}")
print(f"Probabilidades se EaD (1): P(Y=0)={p_x3_y0:.4f} | P(Y=1)={p_x3_y1:.4f}")
print("Regra h3: Se Presencial -> Favorece Pública. Se EaD -> Favorece Privada.")

# Integração numérica para calcular o OVL (Coeficiente de Sobreposição)
def sobreposicao_exponencial(lam0, lam1):
    f0 = lambda x: verossimilhanca_exponencial(x, lam0)
    f1 = lambda x: verossimilhanca_exponencial(x, lam1)
    ovl, _ = quad(lambda x: min(f0(x), f1(x)), 0, np.inf)
    return ovl

ovl_x1 = sobreposicao_exponencial(lambda_x1_y0, lambda_x1_y1)
ovl_x2 = sobreposicao_exponencial(lambda_x2_y0, lambda_x2_y1)

# Para a Bernoulli, a sobreposição é a soma dos mínimos das proporções
ovl_x3 = min(1 - p_x3_y0, 1 - p_x3_y1) + min(p_x3_y0, p_x3_y1)

print("\n--- Ranking de Discriminação (1 - OVL) ---")
print(f"1º X2 (Matrículas): {1 - ovl_x2:.4f}")
print(f"2º X3 (Modalidade): {1 - ovl_x3:.4f}")
print(f"3º X1 (Ingressantes): {1 - ovl_x1:.4f}")

"""## 7. Implementação do Classificador Multivariado
Assumimos aqui a **hipótese de independência condicional**: o classificador calcula a probabilidade matemática assumindo que o número de ingressantes não afeta o número de matrículas.

Para evitar problemas de *underflow* numérico da máquina (multiplicação de probabilidades gerando zeros), implementamos o classificador inteiramente no **domínio logarítmico**. Na função de Bernoulli, aplicamos `np.clip` (Suavização de Laplace) para evitar um erro fatal de `log(0)`.
"""

# Função para a variável categórica com Suavização (Laplace/Epsilon)
def verossimilhanca_bernoulli_suavizada(x, p, eps=1e-6):

    p_suavizado = np.clip(p, eps, 1 - eps)
    # Se x=1 (EaD), retorna p. Se x=0 (Presencial), retorna 1-p.
    return x * p_suavizado + (1 - x) * (1 - p_suavizado)

def prever_naive_bayes_classico(x1, x2, x3):
    # 1. Verossimilhanças isoladas para a classe 0 (Pública)
    lik_x1_0 = verossimilhanca_exponencial(x1, lambda_x1_y0)
    lik_x2_0 = verossimilhanca_exponencial(x2, lambda_x2_y0)
    lik_x3_0 = verossimilhanca_bernoulli_suavizada(x3, p_x3_y0)

    # Teorema de Bayes Clássico (Multiplicação): Priori * p(X1) * p(X2) * p(X3)
    posteriori_0 = p_y0 * lik_x1_0 * lik_x2_0 * lik_x3_0

    # 2. Verossimilhanças isoladas para a classe 1 (Privada)
    lik_x1_1 = verossimilhanca_exponencial(x1, lambda_x1_y1)
    lik_x2_1 = verossimilhanca_exponencial(x2, lambda_x2_y1)
    lik_x3_1 = verossimilhanca_bernoulli_suavizada(x3, p_x3_y1)

    # Teorema de Bayes Clássico (Multiplicação): Priori * p(X1) * p(X2) * p(X3)
    posteriori_1 = p_y1 * lik_x1_1 * lik_x2_1 * lik_x3_1

    # A classe com o maior valor final vence
    return np.where(posteriori_1 > posteriori_0, 1, 0)

"""## 8. Avaliação e Matriz de Confusão
Agora aplicamos a nossa regra de decisão Bayesiana ao arquivo `teste.csv`, que foi isolado e guardado lá no começo.

*   **Verdadeiro Positivo (VP):** Curso privado classificado corretamente como privado.
*   **Verdadeiro Negativo (VN):** Curso público classificado corretamente como público.
*   **Falso Positivo (FP):** Curso público que o modelo se confundiu e rotulou como privado.
*   **Falso Negativo (FN):** Curso privado rotulado incorretamente como público.
"""

df_teste = pd.read_csv('teste.csv', sep=';')

# Realizando as predições com a multiplicação clássica
df_teste['Y_PREDITO'] = prever_naive_bayes_classico(
    df_teste['QT_ING'].values,
    df_teste['QT_MAT'].values,
    df_teste['X3_MODALIDADE'].values
)

cm = confusion_matrix(df_teste['Y_REDE'], df_teste['Y_PREDITO'])
disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=['Pública (0)', 'Privada (1)'])

# O parâmetro values_format='d' força a exibição do número real sem notação científica
disp.plot(cmap='Blues', values_format='d')
plt.title('Matriz de Confusão - Naive Bayes (Teste)')
plt.show()

print("\nRelatório de Métricas Oficiais:")
print(classification_report(df_teste['Y_REDE'], df_teste['Y_PREDITO'], target_names=['0 (Pública)', '1 (Privada)']))

"""## 9. Discussão e Limitações Críticas (Item 16)


1.  **A Falsa Premissa de Independência:** O Naive Bayes assume que Ingressantes e Matrículas ocorrem independentemente. Na realidade educacional, elas são fortemente correlacionadas. Tratar essas duas variáveis como independentes significa que nosso modelo está, na prática, contando a mesma "força de evidência" duas vezes.
2.  **O Paradoxo da Acurácia e Desbalanceamento:** O modelo cravou falsos negativos altos. Como o Brasil possui 95% de cursos privados, o modelo cria um viés gigantesco a favor da classe 1. Uma universidade privada populosa cruza nossa fronteira de 120 matrículas rapidamente, enganando o algoritmo e fazendo-o acreditar que é uma federal, justamente porque o classificador precisa de evidências numéricas extremas para ter a "coragem" de contrariar o *prior*.
"""